def esc(t):
    return json.dumps(t, ensure_ascii=False)[1:-1]

n_edit = 0
for (page, frag), (ntitle, nnote) in E.items():
    items = data[page]
    hit = [it for it in items if frag in it['title']]
    assert len(hit) == 1, '定位失败 %s %s -> %d' % (page, frag, len(hit))
    it = hit[0]
    ot, on = it['title'], it['note']
    ote, one_ = esc(ot), esc(on)
    assert raw.count(ote) == 1, '标题原文不唯一: %r' % ot
    raw = raw.replace(ote, esc(ntitle))
    if nnote is not None:
        assert raw.count(one_) == 1, 'note原文不唯一: %r' % on[:40]
        raw = raw.replace(one_, esc(nnote))
    n_edit += 1
    print('OK', page, '->', ntitle)

