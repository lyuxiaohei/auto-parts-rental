# -*- coding: utf-8 -*-
"""G23 T3 后术语修正：清除废弃词与语境外裸词（读取-精确替换+assert 计数）"""
import io, sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
P = r"P2-R01-产品需求文档.md"
t = open(P, encoding="utf-8").read()

fixes = [
    # (旧, 新, 预期次数)
    ("预付＝预付运营方租金冲抵后续应付", "预付＝预付供应商租金冲抵后续应付", 1),
    ("路凯（围板箱供应商兼运营方）", "路凯（围板箱供应商兼系统对接方）", 1),
    ("（原在租台账职能并入）", "（G07 前独立页职能并入）", 1),
    ("承载原在租台账职能", "承载 G07 前独立在租页职能", 1),
    ("账单带费用分类", "账单带费用类型", 1),
    ("docNo 弱引用单号", "docNo 弱引用来源单据编号", 1),
    ("唯一，=来源单据单号", "唯一，=来源单据编号", 1),
    ("待办主键即单号", "待办主键即单据编号", 1),
    ("M03（`?id=` 单号）", "M03（`?id=` 单据编号）", 1),
    ("以单号互溯（单号即外键，不复制数据）", "以单据编号互溯（单据编号即外键，不复制数据）", 1),
    ("差异走赔偿/盘点兜底", "差异走赔偿/盘点差异处理兜底", 1),
    ("库存查询（多态+下钻+轨迹）、盘点、调拨", "库存查询（多态+下钻+轨迹）、盘点记录、库存调拨", 1),
    ("盘点已完成且有盘亏", "盘点单已完成且有盘亏", 1),
    ("（盘盈关联盘点）", "（盘盈关联盘点单）", 1),
    ("盘点以账面为基准找差异", "盘点单以账面为基准找差异", 1),
    ("在租口径盘点客户端资产", "该口径覆盖客户端在租资产", 1),
]

ok = True
for old, new, n in fixes:
    c = t.count(old)
    if c != n:
        print(f"[FAIL] 「{old[:24]}…」出现 {c} 次（预期 {n}）")
        ok = False
    else:
        t = t.replace(old, new)
        print(f"[PASS] {old[:30]} → {new[:30]}")

if ok:
    open(P, "w", encoding="utf-8", newline="\n").write(t)
    print("\n全部替换已写盘")
else:
    print("\n存在计数不符，未写盘")
    sys.exit(1)
