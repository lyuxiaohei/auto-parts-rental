def R(fields, cells=None, ops=None, keyHtml=None):
    row = {"fields": fields}
    if keyHtml: row["keyHtml"] = keyHtml
    if cells is not None: row["cells"] = cells
    if ops is not None: row["ops"] = ops
    return json.dumps(row, ensure_ascii=False)

def tag(txt, color): return '<span class="tag tag-%s">%s</span>' % (color, txt)
def num(txt): return '<span class="td-num">%s</span>' % txt

def blk(key, row): return "    '%s': { 'row': %s }," % (key, row)

def entity(name, comment, lines):
    out = ['  /* --------------------------------------------------------------------------',
           ' * ' + comment,
           ' * ------------------------------------------------------------------------ */',
           '  %s: {' % name]
    out += lines
    out.append('  },')
    return '\r\n'.join(out)

