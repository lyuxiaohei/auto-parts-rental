def modal_pat(mid):
    return re.compile(
        r'(?:<!-- [^>]*弹窗[^>]*-->\r?\n)?'
        r'<div class="modal-overlay" id="' + mid + r'">.*?关 闭</button>\s*</div>\s*</div>\s*</div>', re.S)

def read(rel):
    return (ROOT / rel).read_bytes().decode('utf-8')

def write(rel, text):
    (ROOT / rel).write_bytes(text.encode('utf-8'))

def backup(rel):
    dst = BACKUP / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / rel, dst)

def skeleton(title, nl, mid, width):
    skel = ('<!-- 弹窗骨架化 · 详情弹窗数据驱动 2026-09-08 -->',
            '<div class="modal-overlay" id="' + mid + '">',
            '  <div class="modal modal-lg" style="width:' + str(width) + 'px;">',
            '    <div class="modal-header">',
            '      <h3 class="modal-title" id="detailTitle">' + title + '</h3>',
            '      <span class="modal-close" onclick="closeModal(\'' + mid + '\')">×</span>',
            '    </div>',
            '    <div class="modal-body" id="detailBody"><!-- 内容由 _data/detail-generic.js 按单号渲染 --></div>',
            '    <div class="modal-footer">',
            '      <button class="btn btn-default" onclick="closeModal(\'' + mid + '\')">关 闭</button>',
            '    </div>', '  </div>', '</div>')
    return nl.join(skel)

def convert_list_page(rel, entity, title, mid='detailModal', anchor='详情', wire_opts=''):
    raw = read(rel)
    assert raw.count('id="' + mid + '"') == 1, rel + ': ' + mid + ' 非唯一'
    if 'id="detailBody"' in raw:
        print('  [skip 已改造]', rel)
        return False
    nl = '\r\n' if '\r\n' in raw else '\n'
    pat = modal_pat(mid)
    m = pat.search(raw)
    assert m, rel + ': ' + mid + ' 块未匹配'
    wm = re.search(r'width:(\d+)px', m.group(0))
    width = int(wm.group(1)) if wm else 780
    wiring = nl.join(['<script src="../_data/demo-data.js"></script>',
                      '<script src="../_data/detail-generic.js"></script>', '<script>',
                      '/* demo-data 接线：各行「' + anchor + '」按行内键渲染对应数据（' + TAG + '） */',
                      "wireDetailModal('" + entity + "'" + wire_opts + ');', '</script>'])
    repl = skeleton(title, nl, mid, width) + nl + wiring
    raw = raw[:m.start()] + repl + raw[m.end():]
    write(rel, raw)
    return True

