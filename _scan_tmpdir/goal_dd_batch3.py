def flowinfo(code, name, cat, prj, stk, transit, client, wait, unit, area, ver=None):
    info = [
        {'label': '物料编码', 'text': code},
        {'label': '名称规格', 'text': name, 'full': True},
        {'label': '物料类别', 'text': cat},
    ]
    if ver:
        info.append({'label': 'BOM 版本', 'text': ver})
    info += [
        {'label': '适用项目', 'text': prj, 'full': True},
        {'label': '在库', 'text': stk + ' ' + unit},
        {'label': '在途（退租未审核）', 'text': transit + ' ' + unit},
        {'label': '客户端（租出）', 'text': client + ' ' + unit},
        {'label': '退租待入库', 'text': wait + ' ' + unit},
        {'label': '库区', 'text': area},
    ]
    return info

def sf(code, name, cat, prj, stk, transit, client, wait, unit, area, flows, chain, timeline, ver=None):
    return (code, {'title': '库存流水', 'titleNo': code + ' ' + name,
        'info': flowinfo(code, name, cat, prj, stk, transit, client, wait, unit, area, ver),
        'feeSecTitle': '进出流水（时间倒序）',
        'feeCols': ['日期', '类型', '单据号', '方向数量', '结存'],
        'fees': flows, 'chain': chain, 'timeline': timeline})

