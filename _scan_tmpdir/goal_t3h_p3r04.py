def main():
    BK.mkdir(parents=True, exist_ok=True)
    if not (BK / F.name).exists():
        shutil.copy2(F, BK / F.name)
    t = F.read_text(encoding="utf-8")
    for old, new in EDITS:
        n = t.count(old)
        assert n == 1, f"锚点计数 {n} != 1: {old[:50]}..."
        t = t.replace(old, new)
    F.write_text(t, encoding="utf-8", newline="")
    # 复核
    rows = re.findall(r'^\| [^|]+\|[^|]+\| (✅|⚠️|❌) ', t, re.M)
    from collections import Counter
    c = Counter(rows)
    print("复评后判定分布:", dict(c), "总:", len(rows))
    assert c.get("⚠️", 0) == 0 and c.get("❌", 0) == 0

if __name__ == "__main__":
    main()
