def read(rel):
    return (ROOT / rel).read_bytes().decode('utf-8')

def write(rel, text):
    (ROOT / rel).write_bytes(text.encode('utf-8'))

def backup(rel):
    dst = BACKUP / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / rel, dst)

def convert_list_page(rel, entity, title):
    raw = read(rel)
    assert raw.count('id="detailModal"') == 1, rel + ': detailModal 非唯一'
    if 'id="detailBody"' in raw:
        print('  [skip 已改造]', rel)
        return False
    m = MODAL_PAT.search(raw)
    assert m, rel + ': detailModal 块未匹配'
    repl = skeleton(title, '_data/detail-generic.js') + '\r\n' + (
        '<script src="../_data/demo-data.js"></script>\r\n'
        '<script src="../_data/detail-generic.js"></script>\r\n'
        '<script>\r\n'
        '/* demo-data 接线：各行「详情」按行内单号渲染对应数据（' + TAG + '） */\r\n'
        'wireDetailModal(\'' + entity + '\');\r\n'
        '</script>')
    raw = raw[:m.start()] + repl + raw[m.end():]
    write(rel, raw)
    return True

