def po_items(content, total=None):
    """'锁扣组件×5,000 / 铰链×2,000' -> fees 行（含合计）"""
    rows, sum_amt, sum_qty = [], 0.0, 0
    for seg in content.split('/'):
        seg = seg.strip()
        m = re.match(r'(.+?)×([\d,]+)', seg)
        name, qty = m.group(1).strip(), int(m.group(2).replace(',', ''))
        code, spec, unit, price = PO_ITEM[name]
        amt = round(qty * float(price), 2) if price else None
        rows.append([code, spec, unit, format(qty, ','), price or '—', format(amt, ',.2f') if amt is not None else '—'])
        sum_qty += qty
        sum_amt += amt or 0
    if total:
        t = float(total.replace(',', ''))
        if abs(t - sum_amt) > 0.01 and len(rows) > 1:
            rows[-1][5] = format(t - (sum_amt - float(rows[-1][5].replace(',', ''))), ',.2f')
            rows[-1][4] = '—'
            sum_amt = t
    rows.append(['', '合计', '', format(sum_qty, ','), '', format(sum_amt, ',.2f')])
    return rows

