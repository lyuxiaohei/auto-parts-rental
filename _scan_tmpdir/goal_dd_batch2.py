def jstr(s):
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'") + "'"

def jser(v, ind):
    pad = ' ' * ind
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return jstr(v)
    if isinstance(v, list):
        if not v:
            return '[]'
        if all(isinstance(x, (str, int, float, bool)) for x in v):
            return '[' + ', '.join(jser(x, 0) for x in v) + ']'
        return '[\n' + (',\n').join(pad + '  ' + jser(x, ind + 2) for x in v) + '\n' + pad + ']'
    if isinstance(v, dict):
        parts = []
        for k, val in v.items():
            if val is None:
                continue
            kk = str(k) if isinstance(k, int) else jstr(k)
            parts.append(pad + '  ' + kk + ': ' + jser(val, ind + 2))
        return '{\n' + ',\n'.join(parts) + '\n' + pad + '}'
    raise TypeError(str(type(v)))

def entity_block(name, comment, records, nl):
    lines = ['  /* ' + '-' * 74 + ' */']
    for c in comment:
        lines.append('  /* ' + c + ' */')
    lines.append('  ' + name + ': {')
    recs = []
    for no, rec in records:
        recs.append('    ' + jstr(no) + ': ' + jser(rec, 4).lstrip())
    lines.append(',\n'.join(recs))
    lines.append('  }')
    return nl.join(lines)

